#!/usr/bin/env python3
"""Pack traced JSONs into styles/flucht/vectors.js: python3 -I pack.py <out.js> name=file.json ..."""
import sys, json
out = sys.argv[1]; D = {}
for arg in sys.argv[2:]:
    n, f = arg.split('=', 1); J = json.load(open(f))
    D[n] = {'w': J['w'], 'h': J['h'], 'order': J['order'], 'layers': {k: {'c': L['c'], 'paths': [[round(v, 1) for v in p] for p in L['paths']]} for k, L in J['layers'].items()}}
open(out, 'w').write('// generated by tools-trace/pack.py from the user\'s own frames (tools-trace/trace3.py) — do not edit by hand\nconst FLV = ' + json.dumps(D, separators=(',', ':')) + ';\n')
print(out, len(open(out).read()) // 1024, 'KB', list(D))
