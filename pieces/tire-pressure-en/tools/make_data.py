# voice/words_asr.json (heard words + times) + the script (display text) -> src/data.js (WORDS, CHUNKS)
import json, re, difflib, sys
P = sys.argv[1]
asr = json.load(open(P + '/voice/words_asr.json'))
script = ("Why is it that you fill your tires at the gas station and the very next morning they're lower? "
 "They're not leaking. Not a single bubble. Every bit of that air is still inside. "
 "Here's why: every time the wheel turns, the rubber gets squashed against the road and springs back, about eight hundred times every mile. "
 "And because rubber that bends that much heats up, it's just like a paper clip you bend back and forth until it's warm. "
 "That heat soaks into the air inside, so the hot air pushes harder. "
 "That's why, at the pump, the gauge reads about four pounds per square inch too high, so you stop filling too early. "
 "Then overnight, the tire cools down, the air shrinks, and the pressure drops by exactly those four pounds per square inch. "
 "It's the same thing that happens to a balloon left in your car on a freezing night: by morning it's wrinkled, even though it hasn't lost any air. "
 "So they didn't go down. They were never really full. "
 "That's why you should check them cold, or if you've just been driving, add four P S I on top. "
 "And if you want more tricks like this for your car, follow this account.")
disp = script.split()
norm = lambda w: re.sub(r"[^A-Z']", '', w.upper())
a = [norm(w['w']) for w in asr]; d = [norm(w) for w in disp]
sm = difflib.SequenceMatcher(None, d, a, autojunk=False)
times = [None]*len(disp)
for tag, i1, i2, j1, j2 in sm.get_opcodes():
    if tag in ('equal', 'replace') and (i2-i1) == (j2-j1):
        for k in range(i2-i1): times[i1+k] = (asr[j1+k]['s'], asr[j1+k]['e'])
    else: print('unaligned', tag, disp[i1:i2], [asr[j]['w'] for j in range(j1, j2)])
assert all(times), [disp[i] for i,t in enumerate(times) if not t]
W = [dict(w=w, s=t[0]) for w, t in zip(disp, times)]
for i, w in enumerate(W): w['e'] = round(W[i+1]['s'] if i+1 < len(W) else w['s'] + 0.45, 3)
# display merges: "eight hundred" -> 800, "four" -> 4, "P S I" -> PSI
out = []; i = 0
while i < len(W):
    w = W[i]
    if w['w'] == 'eight' and W[i+1]['w'] == 'hundred': out.append(dict(w='800', s=w['s'], e=W[i+1]['e'])); i += 2; continue
    if w['w'] == 'P' and W[i+1]['w'] == 'S' and W[i+2]['w'] == 'I': out.append(dict(w='PSI', s=w['s'], e=W[i+2]['e'])); i += 3; continue
    if w['w'] == 'four': w = dict(w, w='4')
    out.append(w); i += 1
W = out
KEY = {'lower?', 'inside.', 'squashed', '800', 'heats', 'paper', 'clip', 'pushes', 'high,', 'early.', 'shrinks,', 'drops', 'freezing', 'wrinkled,', 'full.', 'cold,', 'PSI', 'follow'}
HOT = {'heats', 'up,', 'hot', 'warm.', 'heat', 'high,'}
COLD = {'cold,', 'cools', 'freezing', 'shrinks,', 'overnight,'}
for w in W:
    w['k'] = 1 if w['w'] in KEY else 0
    w['c'] = 'hot' if w['w'] in HOT else 'cold' if w['w'] in COLD else ('bad' if w['w'] in {'lower?', 'drops'} else ('good' if w['w'] in {'full.', 'follow'} else 'plain'))
# chunks: up to 4 words / 18 chars, break after punctuation
CH = []; cur = []
for i, w in enumerate(W):
    cur.append(i)
    txt = ' '.join(W[j]['w'] for j in cur)
    end = re.search(r"[.,?:!]$", w['w']) or len(cur) >= 4 or len(txt) >= 17
    nxt = W[i+1] if i+1 < len(W) else None
    if nxt and len(txt + ' ' + nxt['w']) > 20: end = True
    if end or not nxt: CH.append(dict(a=cur[0], b=cur[-1], t0=W[cur[0]]['s'], t1=(W[i+1]['s'] if nxt else w['e'] + 0.6))); cur = []
for c in CH: c['t0'] = round(c['t0'], 3); c['t1'] = round(c['t1'], 3)
js = '// generated by tools/make_data.py from voice/words_asr.json (word times heard in voice/vo.wav)\n'
js += 'const WORDS = ' + json.dumps(W) + ';\nconst CHUNKS = ' + json.dumps(CH) + ';\n'
js += 'const VOICE_END = %.3f;\n' % W[-1]['e']
js += 'const WT = (txt, n = 1) => { let k = 0; for (const w of WORDS) if (w.w.toLowerCase().replace(/[^a-z0-9\']/g, "") === txt && ++k === n) return w.s; throw new Error("no word " + txt); };\n'
open(P + '/src/data.js', 'w').write(js)
print(len(W), 'words', len(CH), 'chunks, end', W[-1]['e'])
for c in CH: print(f"{c['t0']:6.2f} {' '.join(W[j]['w'] for j in range(c['a'], c['b']+1))}")
