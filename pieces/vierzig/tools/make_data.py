# Builds src/data.js from the trimmed voice-over (voice/vo.wav) and the word timings (voice/words_asr.json):
#   WORDS (on-screen text + timing), CHUNKS (karaoke groups), VENV (loudness per frame, lip-sync), SPEAK (who talks when)
# usage: python3 -I tools/make_data.py <piece dir>
import json, sys, wave, re
import numpy as np
ROOT = sys.argv[1]; FPS = 30
W = json.load(open(f"{ROOT}/voice/words_asr.json"))
words = [{"w": w["w"], "s": w["s"], "e": w["e"]} for w in W]
def merge(i, txt):   # word i absorbs word i+1
    words[i] = {"w": txt, "s": words[i]["s"], "e": words[i + 1]["e"]}; words[i + 1] = None
def find(txt, after=0.0):
    return next(i for i, w in enumerate(words) if w and w["w"] == txt and w["s"] >= after)
# corrections by index (what the script says; the recogniser normalised a few words)
FIX = {3: "sofort?", 5: "1", 19: "1", 22: "schenk", 29: "Straße!", 43: "Willst", 49: "schlafen,", 56: "Multimillionär", 69: "Euro.", 70: "Dann",
       76: "Million.", 77: "Danach", 85: "Million.", 86: "Und", 104: "steinreich!", 109: "Bruder!", 111: "Jonas'", 152: "Sechs", 165: "Na,",
       166: "Jonas?", 178: "aus!", 179: "Genieß", 181: "Aussicht,", 210: "los,", 211: "Jonas.", 212: "Zeig", 217: "hast!"}
for i, t in FIX.items(): words[i]["w"] = t
merge(93, "500.000"); merge(131, "volltankt,")
words = [w for w in words if w]
CLS = [
    ("name", r"^(KEVIN|JONAS|JONAS'|BRUDER)$"),
    ("neg", r"^(ABGERECHNET)$"),
    ("money", r"^(40|MILLIONEN|EURO|1|3|500.000|5|35|MILLION|MULTIMILLIONÄR|STEINREICH|KONTO)$"),
    ("obj", r"^(WECKER|PRIVATINSEL|LAMBORGHINI|PARTY|DUBAI|DIAMANTKETTE|HANDY|LAPTOP|DUSCHE|BUS|VIDEOCALL|TANKFÜLLUNG|MEER|STRAND)$"),
    ("pos", r"^(SEKUNDE|JAHR|WOCHEN|MONATE|TIEFSCHLAF|KRÖNUNG|ZWEI|SECHS)$"),
]
for w in words:
    key = re.sub(r"[.,!:;?…]+$", "", w["w"].upper()); w["c"] = "plain"
    for c, rx in CLS:
        if re.match(rx, key): w["c"] = c; break
# caption chunks: <= 3 words / 18 chars, break after . ? ! : , and on pauses
chunks, cur = [], []
for i, w in enumerate(words):
    cur.append(i); nxt = words[i + 1] if i + 1 < len(words) else None
    txt = " ".join(words[k]["w"] for k in cur)
    end = (re.search(r"[.?!:…]$", w["w"]) is not None) or nxt is None or (nxt["s"] - w["e"] > 0.28) \
        or len(cur) >= 3 or len(txt) >= 18 or (w["w"].endswith(",") and len(cur) >= 2)
    if end: chunks.append(cur); cur = []
CH = [{"a": c[0], "b": c[-1], "t0": words[c[0]]["s"], "t1": words[c[-1]]["e"]} for c in chunks]
for i, c in enumerate(CH):
    nx = CH[i + 1]["t0"] if i + 1 < len(CH) else c["t1"] + 0.8
    c["t1"] = round(min(max(c["t1"] + 0.25, c["t0"] + 0.6), nx), 3)
wv = wave.open(f"{ROOT}/voice/vo.wav"); sr = wv.getframerate()
x = np.frombuffer(wv.readframes(wv.getnframes()), np.int16).astype(np.float32) / 32768
hop = sr // FPS; n = len(x) // hop
rms = np.sqrt(np.mean(x[: n * hop].reshape(n, hop) ** 2, axis=1)); ref = np.percentile(rms[rms > 0.01], 90)
VENV = [round(float(v), 2) for v in np.clip(rms / ref, 0, 1.2)]
SPEAK = [["kevin", 6.82, 9.78], ["kevin", 13.6, 16.66], ["kevin", 32.06, 36.58], ["kevin", 54.84, 59.02], ["jonas", 59.24, 61.08], ["kevin", 67.4, 69.34]]
out = "// ---- generated by tools/make_data.py from voice/vo.wav + voice/words_asr.json (do not edit)\n"
out += "const WORDS = " + json.dumps(words, ensure_ascii=False) + ";\n" + "const CHUNKS = " + json.dumps(CH) + ";\n"
out += "const VENV = " + json.dumps(VENV) + ";\n" + "const SPEAK = " + json.dumps(SPEAK) + ";\n" + f"const VO_DUR = {len(x) / sr:.3f};\n"
open(f"{ROOT}/src/data.js", "w").write(out)
print(len(words), "words,", len(CH), "chunks, vo", round(len(x) / sr, 2), "s")
for c in CH: print(f'{c["t0"]:6.2f}-{c["t1"]:6.2f}', " ".join(words[k]["w"] + "/" + words[k]["c"][0] for k in range(c["a"], c["b"] + 1)))
