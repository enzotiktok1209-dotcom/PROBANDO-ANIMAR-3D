# Builds src/data.js from the trimmed voice-over:
#   WORDS   – every spoken word with its start/end (heard by faster-whisper) and the text shown on screen
#   CHUNKS  – karaoke caption groups (2-4 words), split on punctuation and pauses
#   VENV    – the voice loudness per video frame (30 fps), drives the lip-sync
#   SPEAK   – who is talking when (dani / leo / bote / narrator)
# usage: python3 -I tools/make_data.py <piece dir>
import json, sys, wave, re
import numpy as np

ROOT = sys.argv[1]
FPS = 30
W = json.load(open(f"{ROOT}/voice/words_asr.json"))

# ---- corrections: what is shown on screen
words = [{"w": w["w"], "s": w["s"], "e": w["e"]} for w in W]
fix = {4: "zocken…", 19: "Hahaha!", 22: "Baby!", 27: "Bürozeug!", 54: "live.", 64: "Euro!", 72: "Zocken!", 96: "Kuli.", 98: "Kuli",
       140: "PlayStation.", 209: "Jonas'", 1: "Einziger"}
for i, t in fix.items(): words[i]["w"] = t
words[19]["s"] = 7.75
# numbers the ASR split ("1" ".200")
for i in range(len(words)):
    w = words[i]
    if w and re.match(r"^\.\d{3}", w["w"]) and i > 0 and words[i - 1]:
        words[i - 1] = {"w": words[i - 1]["w"] + w["w"], "s": words[i - 1]["s"], "e": w["e"]}; words[i] = None
words = [w for w in words if w]
# ---- colour classes (karaoke highlight colour)
CLS = [
    ("name", r"^(KEVIN|KEVINS|JONAS|JONAS'|BABY|LEUTE|STREAMER)$"),
    ("neg", r"^(NEIN|STROMAUSFALL|WEG|NIEMALS|AUSGELACHT)$"),
    ("money", r"^(MILLION|CENT|EURO|450|30|25|5,12|1|2|4|8|15|20|27|DREI|GOLD|50ER|40-EURO-SHAKE|KLEINGELD|CENT-MAGNAT|TAGE|TAG|SEKUNDEN|ERBE)$"),
    ("obj", r"^(GTA|PLAYSTATION|BÜROKLAMMER|BÜROKLAMMER\?|KULI|LAMPE|CAMPINGKOCHER|STROMGENERATOR|GENERATOR|MOPED|LIEFERWAGEN|AUTO|HAUS|KNOPF|STREAM|STREAMS|BÜROZEUG)$"),
    ("pos", r"^(REICH|LIVE|TAUSCHEN|BESSER|GLEICHSTAND|PLAN|ZOCKEN)$"),
]
for w in words:
    key = re.sub(r"[.,!:;]+$", "", w["w"].upper())
    w["c"] = "plain"
    for c, rx in CLS:
        if re.match(rx, key): w["c"] = c; break
    if w["c"] == "plain" and re.search(r"\d|EURO|CENT", key): w["c"] = "money"

# ---- caption chunks: <= 3 words / 18 chars, break after . ? ! : , and on pauses > 0.28 s
chunks, cur = [], []
for i, w in enumerate(words):
    cur.append(i)
    nxt = words[i + 1] if i + 1 < len(words) else None
    txt = " ".join(words[k]["w"] for k in cur)
    end = (re.search(r"[.?!:…]$", w["w"]) is not None) or nxt is None or (nxt["s"] - w["e"] > 0.28) \
        or len(cur) >= 3 or len(txt) >= 18 or (w["w"].endswith(",") and len(cur) >= 2)
    if end: chunks.append(cur); cur = []
CH = []
for c in chunks:
    CH.append({"a": c[0], "b": c[-1], "t0": words[c[0]]["s"], "t1": words[c[-1]]["e"]})
# each chunk stays until the next starts (or +0.5 s), at least 0.6 s
for i, c in enumerate(CH):
    nx = CH[i + 1]["t0"] if i + 1 < len(CH) else c["t1"] + 0.8
    c["t1"] = round(min(max(c["t1"] + 0.25, c["t0"] + 0.6), nx), 3)

# ---- loudness envelope per frame
wv = wave.open(f"{ROOT}/voice/vo.wav"); sr = wv.getframerate()
x = np.frombuffer(wv.readframes(wv.getnframes()), np.int16).astype(np.float32) / 32768
hop = sr // FPS; n = len(x) // hop
rms = np.sqrt(np.mean(x[: n * hop].reshape(n, hop) ** 2, axis=1))
ref = np.percentile(rms[rms > 0.01], 90)
env = np.clip(rms / ref, 0, 1.2)
VENV = [round(float(v), 2) for v in env]

# ---- who speaks (line spans in the trimmed voice)
SPEAK = [
    ["kevin", 7.7, 12.15], ["kevin", 25.1, 28.0], ["kevin", 44.3, 45.95], ["jonas", 51.1, 53.1], ["kevin", 53.7, 55.5], ["jonas", 72.9, 74.15],
]
out = "// ---- generated by tools/make_data.py from voice/vo.wav + voice/words_asr.json (do not edit)\n"
out += "const WORDS = " + json.dumps(words, ensure_ascii=False) + ";\n"
out += "const CHUNKS = " + json.dumps(CH) + ";\n"
out += "const VENV = " + json.dumps(VENV) + ";\n"
out += "const SPEAK = " + json.dumps(SPEAK) + ";\n"
out += f"const VO_DUR = {len(x) / sr:.3f};\n"
open(f"{ROOT}/src/data.js", "w").write(out)
print(len(words), "words,", len(CH), "chunks,", len(VENV), "env frames, vo", round(len(x) / sr, 2), "s")
for c in CH: print(f'{c["t0"]:6.2f}-{c["t1"]:6.2f}', " ".join(words[k]["w"] + "/" + words[k]["c"][0] for k in range(c["a"], c["b"] + 1)))
